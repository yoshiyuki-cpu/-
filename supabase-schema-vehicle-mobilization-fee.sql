-- 重機の回送費をマスタに登録できるようにする。
--
-- これまで回送費は、現場でその重機を初めて車両代に記録するときに毎回手入力していた。
-- 実際には機種ごとにほぼ決まった額（積む車が変わらないため）なので、マスタに持たせて
-- 入力画面で自動入力し、現場によって変わるときだけその場で直す運用にする。
--
-- 単価（default_price）と同じく空欄可。
--   空欄  = 登録なし。今まで通り入力画面で毎回入れる
--   0     = この車両は回送費なし（自走するトラックなど）。入力画面で0のまま保存でき、
--           回送費の行は作らない
alter table vehicles add column if not exists default_mobilization_fee numeric(10,2);
